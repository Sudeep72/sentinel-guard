"""Password hashing (users) and API key generation/hashing (agents).

Two different hashing strategies are used deliberately:

- **User passwords** use bcrypt (adaptive, slow-by-design), because
  human passwords are low-entropy and vulnerable to offline brute-force
  if the hash is ever leaked — bcrypt's cost factor is the defense.
- **Agent API keys** use SHA-256 (fast, deterministic), because the key
  itself is a 256-bit random token generated by ``secrets.token_urlsafe``
  — it already has enough entropy that brute-forcing the hash is
  infeasible, and a deterministic hash lets the dashboard look up a
  server by exact hash match (`WHERE api_key_hash = ?`) in O(1), which
  bcrypt's per-call random salt makes impossible without iterating
  every server's hash on every request.
"""

from __future__ import annotations

import hashlib
import secrets

import bcrypt


def hash_password(password: str) -> str:
    """Hash a user password with bcrypt."""
    return bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt()).decode("utf-8")


def verify_password(password: str, hashed_password: str) -> bool:
    """Verify a user password against its bcrypt hash."""
    return bcrypt.checkpw(password.encode("utf-8"), hashed_password.encode("utf-8"))


def generate_api_key() -> str:
    """Generate a new high-entropy API key for a registering agent."""
    return secrets.token_urlsafe(32)


def hash_api_key(api_key: str) -> str:
    """Hash an API key with SHA-256 for storage and exact-match lookup."""
    return hashlib.sha256(api_key.encode("utf-8")).hexdigest()
